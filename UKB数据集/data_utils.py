#### Parsing a date variable from string to timestamp (int64)
# NOTE: The string MUST BE in the format of "YYYY-MM-DD" (see assertion).
#       OFFSET_YEAR is used to avoid the parsing error of the "datetime" library.
def date_from_string(raw_date: str):
    assert len(raw_date) == 10 and raw_date[0:4].isdigit() and raw_date[4] == "-" and \
        raw_date[5:7].isdigit() and raw_date[7] == "-" and raw_date[8:10].isdigit()
    return datetime.datetime(int(raw_date[0:4]) + OFFSET_YEAR, int(raw_date[5:7]), int(raw_date[8:10])).timestamp()

#### Parsing a date variable from timestamp (int64) to string
def string_from_date(date: int):
    raw_date = datetime.datetime.fromtimestamp(date)
    return "{0:04d}".format(raw_date.year - OFFSET_YEAR) + "-" + "{0:02d}".format(raw_date.month) + "-" + \
        "{0:02d}".format(raw_date.day)

#### Parsing a time variable from string to timestamp (int64)
# NOTE: The string MUST BE in the format of "YYYY-MM-DDThh:mm:ssZ" (see assertion).
#       OFFSET_YEAR is used to avoid the parsing error of the "datetime" library.
def time_from_string(raw_time: str):
    assert len(raw_time) == 20 and raw_time[0:4].isdigit() and raw_time[4] == "-" and \
        raw_time[5:7].isdigit() and raw_time[7] == "-" and raw_time[8:10].isdigit() and \
        raw_time[10] == "T" and raw_time[11:13].isdigit() and raw_time[13] == ":" and \
        raw_time[14:16].isdigit() and raw_time[16] == ":" and raw_time[17:19].isdigit() and raw_time[19] == "Z"
    return datetime.datetime(int(raw_time[0:4]) + OFFSET_YEAR, int(raw_time[5:7]), int(raw_time[8:10]), \
        hour=int(raw_time[11:13]), minute=int(raw_time[14:16]), second=int(raw_time[17:19])).timestamp()

#### Parsing a time variable from timestamp (int64) to string
def string_from_time(date: int):
    raw_time = datetime.datetime.fromtimestamp(date)
    return "{0:04d}".format(raw_time.year - OFFSET_YEAR) + "-" + "{0:02d}".format(raw_time.month) + "-" + \
        "{0:02d}".format(raw_time.day) + "T" + "{0:02d}".format(raw_time.hour) + ":" + \
        "{0:02d}".format(raw_time.minute) + ":" + "{0:02d}".format(raw_time.second) + "Z"

#### Seconds per year (to compute year/age by timestamp)
SECONDS_PER_YEAR = 31536000.

#### Getting age from year-of-birth, month-of-birth, and date-of-visit
# NOTE: the computed age is slightly larger because leap year is not considered in SECONDS_PER_YEAR.
def get_age_of_visit(feature_dir):
    year_of_birth = np.load(os.path.join(feature_dir, FIELD_ID_YOB + ".npz"))["feature"][:, 0].astype(np.int32) + OFFSET_YEAR
    month_of_birth = np.load(os.path.join(feature_dir, FIELD_ID_MOB + ".npz"))["feature"][:, 0].astype(np.int32)
    date_of_visit = np.load(os.path.join(feature_dir, FIELD_ID_DOV + ".npz"))["feature"][:, 0].astype(np.float64)
    age_of_visit = np.zeros_like(date_of_visit, dtype=np.float64)
    for n in range(age_of_visit.shape[0]):
        date_of_birth = datetime.datetime(year_of_birth[n], month_of_birth[n], 15).timestamp()
        age_of_visit[n] = (date_of_visit[n] - date_of_birth) / SECONDS_PER_YEAR
    return age_of_visit

#### Getting year-of-visit from date-of-visit
def get_year_of_visit(feature_dir):
    date_of_visit = np.load(os.path.join(feature_dir, FIELD_ID_DOV + ".npz"))["feature"][:, 0].astype(np.int64)
    year_of_visit = np.zeros_like(date_of_visit, dtype=np.float64)
    for n in range(year_of_visit.shape[0]):
        year_of_visit[n] = datetime.datetime.fromtimestamp(date_of_visit[n]).year - OFFSET_YEAR
    return year_of_visit

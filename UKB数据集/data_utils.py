#### The shared function to determine if a coding has a special value (by coding, value, dicts)
def has_sv_operator(coding, sv_dict, op, regular_dict, special_dict):
    for key, _ in sv_dict.items():
        if coding in special_dict and key in special_dict[coding]:
            if special_dict[coding][key] == op:
                return True
        elif key in regular_dict:
            if regular_dict[key] == op:
                return True
    return False

#### The shared function to get special value operator (by coding, value, dicts)
def get_sv_operator(coding, key, regular_dict, special_dict):
    if coding in special_dict and key in special_dict[coding]:
        return special_dict[coding][key]
    elif key in regular_dict:
        return regular_dict[key]
    else:
        return SV_NOT_RECOGNIZED


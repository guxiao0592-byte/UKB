def load_numpy_data(numpy_data_filename):
    return np.load(numpy_data_filename, allow_pickle=True)["data"]

#### Loading feature
def load_feature(feature_filename):
    return np.load(feature_filename)["feature"]

#### Processing a key value in coding (string) to avoid preserved characters in ConfigParser
def config_parser_key(key: str):
    if key[0] == "[" and key[-1] == "]":
        key = "<" + key[1: -1] + ">"
    return key.replace(":", "-").replace("=", "-")

#### Getting index name from field_id, instance ID, and array ID
def get_header_name(field_id, instance_id, array_id):
    return field_id + "-" + str(instance_id) + "." + str(array_id)

#### Getting information from a header
def get_header_info(header: str):
    assert header.count("-") == 1 and header.count(".") == 1
    ind1 = header.index("-")
    ind2 = header.index(".")
    assert ind1 > 0 and ind1 + 1 < ind2 and ind2 + 1 < len(header)
    assert header[:ind1].isnumeric() and header[ind1+1: ind2].isnumeric() and header[ind2+1:].isnumeric()
    return int(header[:ind1]), int(header[ind1+1: ind2]), int(header[ind2+1:])

#### Converting bytes array to string
def string_from_bytes(x):
    return str(x, encoding=TEXT_ENCODER)

